import assert from 'node:assert/strict';
import test from 'node:test';
import { PptxZip, PPTX_LIMITS, rasterDimensions } from '../public/pptx-zip.mjs';
import { resolvePart, PptxPreview } from '../public/pptx-preview.mjs';
import { pptxFixture, pptxEntries, zipFixture } from './fixtures/pptx-fixture.mjs';
const buffer = bytes => bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
test('PPTX indexes compressed entries without inflating unrelated slides or notes', async () => {
  const zip = new PptxZip(buffer(pptxFixture()));
  assert.equal(zip.actual, 0);
  assert.match(new TextDecoder().decode(await zip.read('ppt/slides/slide9.xml')), /PPTX简化预览测试/);
  assert.equal(zip.seen.has('ppt/notesSlides/notesSlide1.xml'), false);
  assert.equal(zip.seen.has('ppt/slides/slide2.xml'), false);
  assert.equal(resolvePart('ppt/slides/slide9.xml', '../media/image1.png'), 'ppt/media/image1.png');
  assert.throws(() => resolvePart('ppt/presentation.xml', '../../outside'), /越界/);
  assert.throws(() => resolvePart('ppt/slides/slide9.xml', 'https://example.invalid/x'), /异常/);
});
test('PPTX rejects damaged, encrypted, unsafe and oversized ZIP structures', async () => {
  assert.throws(() => new PptxZip(new ArrayBuffer(PPTX_LIMITS.file + 1)), /10MiB/);
  assert.throws(() => new PptxZip(buffer(Buffer.from('bad'))), /损坏/);
  assert.throws(() => new PptxZip(buffer(zipFixture({ ...pptxEntries, '../escape.xml': 'x' }))), /异常路径/);
  const encrypted = zipFixture(pptxEntries); const first = encrypted.indexOf(Buffer.from([0x50, 0x4b, 1, 2])); encrypted.writeUInt16LE(0x801, first + 8);
  assert.throws(() => new PptxZip(buffer(encrypted)), /加密/);
  const huge = zipFixture(pptxEntries); const cd = huge.indexOf(Buffer.from([0x50, 0x4b, 1, 2])); huge.writeUInt32LE(PPTX_LIMITS.expanded + 1, cd + 24);
  assert.throws(() => new PptxZip(buffer(huge)), /100MiB/);
  const corrupted = zipFixture(pptxEntries); corrupted[100] ^= 1;
  const zip = new PptxZip(buffer(corrupted));
  await assert.rejects(zip.read('[Content_Types].xml'), /校验/);
  const unsupported = zipFixture(pptxEntries); const c = unsupported.indexOf(Buffer.from([0x50, 0x4b, 1, 2])); unsupported.writeUInt16LE(99, c + 10);
  assert.throws(() => new PptxZip(buffer(unsupported)), /压缩方式/);
  const tooMany = zipFixture(pptxEntries); tooMany.writeUInt16LE(5001, tooMany.length - 14); tooMany.writeUInt16LE(5001, tooMany.length - 12);
  assert.throws(() => new PptxZip(buffer(tooMany)), /5000/);
  const understated = pptxFixture(); const start = understated.indexOf(Buffer.from([0x50, 0x4b, 1, 2])); understated.writeUInt32LE(1, start + 24);
  const understatedZip = new PptxZip(buffer(understated));
  await assert.rejects(understatedZip.read('[Content_Types].xml'), /实际解压/);
});
test('embedded raster dimensions are checked before browser image decoding', () => {
  assert.deepEqual(rasterDimensions(buffer(pptxEntries['ppt/media/image1.png']), 'png'), [1, 1]);
  const huge = Buffer.from(pptxEntries['ppt/media/image1.png']); huge.writeUInt32BE(100000, 16); huge.writeUInt32BE(100000, 20);
  const [width, height] = rasterDimensions(buffer(huge), 'png');
  assert.ok(width * height > 8000000);
  assert.equal(rasterDimensions(buffer(Buffer.from('unknown')), 'jpg'), null);
});
test('PPTX retains only three recent pages and releases resources when evicted or closed', async t => {
  const names = ['document', 'DOMParser', 'Worker'];
  const original = Object.fromEntries(names.map(name => [name, Object.getOwnPropertyDescriptor(globalThis, name)]));
  t.after(() => { for (const name of names) { if (original[name]) Object.defineProperty(globalThis, name, original[name]); else delete globalThis[name]; } });
  const element = () => ({ children: [], style: {}, setAttribute() {}, append(child) { this.children.push(child); } });
  globalThis.document = { createElement: element };
  globalThis.DOMParser = class { parseFromString() { return { documentElement: { getAttribute: () => '' }, getElementsByTagName: () => [], getElementsByTagNameNS: (_ns, name) => name === 'spTree' ? [{ children: [] }] : [] }; } };
  let terminated = false;
  globalThis.Worker = class { terminate() { terminated = true; } };
  const revoked = []; t.mock.method(URL, 'revokeObjectURL', value => revoked.push(value));
  const preview = new PptxPreview(); preview.order = ['ppt/slides/1.xml', 'ppt/slides/2.xml', 'ppt/slides/3.xml', 'ppt/slides/4.xml'];
  preview.text = async () => '<fixture/>';
  for (const page of [1, 2, 3]) await preview.page(page);
  preview.cache.get(1).urls.push('blob:evicted'); preview.urls.add('blob:evicted');
  await preview.page(4);
  assert.equal(preview.cache.size, 3); assert.equal(preview.cache.has(1), false); assert.deepEqual(revoked, ['blob:evicted']);
  preview.cache.get(4).urls.push('blob:closed'); preview.urls.add('blob:closed');
  preview.close();
  assert.equal(terminated, true); assert.equal(preview.cache.size, 0); assert.deepEqual(revoked, ['blob:evicted', 'blob:closed']);
});
