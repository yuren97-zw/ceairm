import {DatabaseSync} from 'node:sqlite';
import {migrateAuthorizationNine} from '../authorization-import.mjs';
import assert from 'node:assert/strict';
import {AUTHORIZATION_HEADERS,authorizationDate} from '../authorization-import.mjs';
function testMigration(){
 const d=new DatabaseSync(':memory:');
 d.exec(`create table settings(key text primary key,value text,updated_at text);
 create table personnel_authorizations(id text,certificate_no text);insert into personnel_authorizations values('old','cert');
 create table personnel_import_batches(id text,import_type text);insert into personnel_import_batches values('auth','authorization'),('person','personnel');
 create table personnel_import_issues(id text,batch_id text);insert into personnel_import_issues values('a','auth'),('p','person');
 create table personnel_change_logs(id text,field_name text,source_batch_id text);insert into personnel_change_logs values('a','authorization.old.status',''),('p','name','person');
 create table personnel_field_overrides(person_id text,field_name text);insert into personnel_field_overrides values('a','authorization.old.status'),('p','name');
 create table master_data_dictionary_values(category text,source_batch_id text);insert into master_data_dictionary_values values('authorization_type','auth'),('course','person');`);
 const options={now:()=>new Date().toISOString(),randomId:()=>crypto.randomUUID(),allowReset:true,audit:()=>{}};
 assert.throws(()=>migrateAuthorizationNine(d,{...options,allowReset:false}),/显式/);
 assert.throws(()=>migrateAuthorizationNine(d,{...options,audit:()=>{throw Error('rollback-test')}}),/rollback-test/);
 assert.equal(d.prepare('select certificate_no from personnel_authorizations').get().certificate_no,'cert');
 assert.equal(d.prepare('select count(*) as n from personnel_import_batches').get().n,2);
 migrateAuthorizationNine(d,options);migrateAuthorizationNine(d,options);
 assert.equal(d.prepare('select count(*) as n from personnel_authorizations').get().n,0);
 assert.equal(d.prepare('select import_type from personnel_import_batches').get().import_type,'personnel');
 assert.equal(d.prepare('select field_name from personnel_change_logs').get().field_name,'name');
 assert.equal(d.prepare('select field_name from personnel_field_overrides').get().field_name,'name');
 assert.equal(d.prepare('select category from master_data_dictionary_values').get().category,'course');
 d.close();
}
export async function testAuthorizationReplacement({request,cookie,db}){
 testMigration();
 const call=async(url,options={})=>(await request(url,{cookie,...options})).data;
 const person=async(no)=>(await call('/personnel',{method:'POST',expected:201,body:{employeeNo:no,name:'替换验收'+no,administrativeTeamId:db.prepare("select id from organization_units where code='TEAM-LINE-1'").get().id}})).person;
 const a=await person('89100001'),b=await person('89100002');
 for(const code of ['REP-A','REP-B','REP-C'])await call('/personnel/authorization-projects',{method:'POST',expected:201,body:{projectCode:code,projectName:code,category:'other'}});
 const row=(p,code,unit='单位甲')=>[p.employeeNo,p.name,code,'','145',unit,'2026-01-01','2030-01-01','有效'];
 const stage=async rows=>(await call('/personnel/imports',{method:'POST',expected:201,body:{type:'authorization',rows:[AUTHORIZATION_HEADERS,...rows]}})).batch;
 const confirm=(batch,expected=200)=>call('/personnel/imports/'+batch.id+'/confirm',{method:'POST',expected,body:{confirmReplacement:true}});
 const rows=id=>db.prepare('select * from personnel_authorizations where person_id=? order by id').all(id);
 let first=await stage([row(a,'REP-A'),row(a,'REP-B'),row(a,'REP-C','单位乙'),row(b,'REP-A')]);
 await call('/personnel/imports/'+first.id+'/confirm',{method:'POST',expected:400});
 assert.equal(rows(a.id).length,0);
 await confirm(first);
 const {capabilityService}=await import('../server.mjs');
 const actor=(await call('/me')).user,space='department:'+db.prepare("select department_id from personnel where id=?").get(a.id).department_id;
 const capabilityBefore=capabilityService.snapshot(actor,space);
 assert.ok(capabilityBefore.projects.some(p=>p.code==='REP-C'));
 const bBefore=rows(b.id),replace=await stage([row(a,'REP-A'),row(a,'REP-B')]);
 assert.equal(replace.summary.replacement.personCount,1);
 assert.equal(replace.summary.replacement.oldCount,3);
 assert.equal(replace.summary.replacement.newCount,2);
 assert.equal(replace.summary.replacement.removedCount,1);
 await confirm(replace);assert.equal(rows(a.id).length,2);assert.deepEqual(rows(b.id),bBefore);
 const capabilityAfter=capabilityService.snapshot(actor,space);
 assert.ok(!capabilityAfter.projects.some(p=>p.code==='REP-C'));
 assert.deepEqual(capabilityAfter.states,capabilityBefore.states);
 const stable=rows(a.id);
 await confirm(replace,409);assert.deepEqual(rows(a.id),stable);
 const bad=await stage([row(a,'REP-A'),row(a,'REP-A')]);assert.ok(bad.summary.errors);await confirm(bad,400);assert.deepEqual(rows(a.id),stable);
 const invalid=row(a,'REP-A');invalid[6]='2026-02-30';
 assert.ok((await stage([invalid])).summary.errors);
 const mismatch=row(a,'REP-A');mismatch[1]='错误姓名';assert.ok((await stage([mismatch])).summary.errors);
 for(const header of ['证书号码','授权备注','培训到限日期'])await call('/personnel/imports',{method:'POST',expected:400,body:{type:'authorization',rows:[[...AUTHORIZATION_HEADERS,header],[...row(a,'REP-A'),'旧值']]}});
 const old=await stage([row(a,'REP-C')]),newer=await stage([row(a,'REP-A')]);
 await confirm(newer);await confirm(old,409);
 const manual=await stage([row(a,'REP-B')]);
 await call('/personnel/'+a.id+'/qualifications/authorization/'+rows(a.id)[0].id,{method:'PUT',body:{authorizationStatus:'暂停',reason:'人工修改'}});
 await confirm(manual,409);
 await call('/personnel/'+a.id+'/qualifications/authorization/'+rows(a.id)[0].id,{method:'PUT',expected:400,body:{trainingExpiresAt:'2030-01-01',reason:'旧字段拒绝'}});
 const rollback=await stage([row(a,'REP-B')]),beforeFailure=rows(a.id);
 db.exec("create trigger auth_replacement_test_fail before insert on personnel_authorizations when new.project_code='REP-B' begin select raise(abort,'模拟写入失败'); end");
 await confirm(rollback,500);assert.deepEqual(rows(a.id),beforeFailure);
 db.exec('drop trigger auth_replacement_test_fail');
 await confirm(rollback);assert.equal(rows(a.id)[0].project_code,'REP-B');
 assert.deepEqual(rows(b.id),bBefore);
 assert.ok(!db.prepare('pragma table_info(personnel_authorizations)').all().some(c=>['certificate_no','training_expires_at','meets_requirements'].includes(c.name)));
 assert.equal(authorizationDate('2026/9/4'),'2026-09-04');
 assert.throws(()=>authorizationDate('2026-02-30'));
 console.log('通过：九字段、主动确认、逐人全量替换、跨单位移除、其他人员保留、重复/非法输入、版本冲突、人工修改冲突及事务回滚。');
}
